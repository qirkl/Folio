# Turn whatever font files are sitting in src/assets/fonts into @font-face rules.
#
#   pwsh -File tools/make_fonts.ps1
#
# Writes src/assets/fonts.css, which the app links on start. Anything declared
# there shows up in the note font picker too, because the picker merges the
# system font list with whatever document.fonts reports - one source of truth,
# no list to keep in sync by hand.
#
# Family, weight and style come from the file name: everything before the last
# dash is the family (dashes become spaces), the last segment names the weight
# or style. Inter-Regular.ttf -> Inter 400; Inter-Bold.ttf -> Inter 700;
# "EB Garamond-SemiBold.ttf" -> "EB Garamond" 600.
#
# Keep this file ASCII-only: PowerShell 5.1 reads .ps1 as ANSI unless it has a
# byte-order mark, so a smart quote or em dash here becomes a parse error.

param(
    [string]$Dir = "$PSScriptRoot\..\src\assets\fonts",
    [string]$Out = "$PSScriptRoot\..\src\assets\fonts.css"
)

$ErrorActionPreference = 'Stop'

$weights = @{
    thin = 100; hairline = 100; extralight = 200; ultralight = 200; light = 300
    regular = 400; normal = 400; book = 400; medium = 500
    semibold = 600; demibold = 600; bold = 700; extrabold = 800; ultrabold = 800
    black = 900; heavy = 900
}
$styles = @{ italic = 'italic'; oblique = 'italic' }
$formats = @{ '.woff2' = 'woff2'; '.woff' = 'woff'; '.ttf' = 'truetype'; '.otf' = 'opentype' }

if (-not (Test-Path $Dir)) { New-Item -ItemType Directory -Force $Dir | Out-Null }

$files = Get-ChildItem $Dir -File |
    Where-Object { $formats.ContainsKey($_.Extension.ToLower()) } |
    Sort-Object Name

$rules = @(
    '/* Generated by tools/make_fonts.ps1 - do not edit by hand.',
    '   Drop font files in src/assets/fonts and re-run the script. */'
)

foreach ($f in $files) {
    $stem = [System.IO.Path]::GetFileNameWithoutExtension($f.Name)
    $parts = $stem -split '-'
    $last = $parts[-1].ToLower()
    $weight = 400
    $style = 'normal'
    $familyParts = $parts

    # The trailing token may name a weight, a style, or both run together
    # ("SemiBoldItalic"). Match the longest weight name first, or "bold" would
    # claim "semibold" and "demibold" on the way past.
    $weightNames = $weights.Keys | Sort-Object Length -Descending
    $styleNames = $styles.Keys | Sort-Object Length -Descending
    $foundWeight = $null
    $foundStyle = $null
    foreach ($name in $weightNames) {
        if ($last -like "*$name*") { $foundWeight = $weights[$name]; break }
    }
    foreach ($name in $styleNames) {
        if ($last -like "*$name*") { $foundStyle = $styles[$name]; break }
    }

    if ($parts.Count -gt 1 -and ($foundWeight -or $foundStyle)) {
        if ($foundWeight) { $weight = $foundWeight }
        if ($foundStyle) { $style = $foundStyle }
        $familyParts = $parts[0..($parts.Count - 2)]
    }

    $family = ($familyParts -join ' ').Trim()
    $format = $formats[$f.Extension.ToLower()]

    $rules += ''
    $rules += "/* $($f.Name) */"
    $rules += '@font-face {'
    $rules += "  font-family: '$family';"
    $rules += "  src: url('assets/fonts/$($f.Name)') format('$format');"
    $rules += "  font-weight: $weight;"
    $rules += "  font-style: $style;"
    $rules += '  font-display: swap;'
    $rules += '}'
    "  $($f.Name)  ->  $family  $weight $style"
}

if ($files.Count -eq 0) { "no font files in $Dir - writing an empty stylesheet" }

# No BOM: a byte-order mark at the top of a stylesheet is best avoided.
[System.IO.File]::WriteAllText($Out, ($rules -join "`n") + "`n", (New-Object System.Text.UTF8Encoding($false)))
"wrote $Out"
